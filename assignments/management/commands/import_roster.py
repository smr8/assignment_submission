class Command(BaseCommand):
    help = "导入花名册学生信息"

    def handle(self, *args, **options):
        created = 0
        skipped = 0

        for student_id, name in ROSTER:
            if User.objects.filter(student_id=student_id).exists():
                self.stdout.write(self.style.WARNING(f"跳过已存在: {student_id} {name}"))
                skipped += 1
                continue

            User.objects.create_user(
                student_id=student_id,
                name=name,
                password="123456",
                is_staff=False,
                is_active=True,
            )
            self.stdout.write(self.style.SUCCESS(f"已创建: {student_id} {name}"))
            created += 1

        self.stdout.write("")
        self.stdout.write(self.style.SUCCESS(f"导入完成: 新增 {created} 人, 跳过 {skipped} 人"))
